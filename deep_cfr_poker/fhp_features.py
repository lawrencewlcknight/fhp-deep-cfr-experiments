from collections import OrderedDict

import numpy as np


ENCODER_ID = "fhp_lossless_suit_canonical_v1"
FEATURE_SIZE = 183
# Original feature order: 138 binary card/player/round/history values, then
# normalised rank/suit counts, pocket-pair/suited flags and nine hand categories.
DENOMINATORS = np.asarray([1] * 138 + [2] * 13 + [3] * 13 +
                          [2] * 4 + [3] * 4 + [1] * 11, dtype=np.float32)


def _canonicalise_suits(*channels):
    signatures = [tuple(float(value) for channel in channels for value in channel[suit])
                  for suit in range(4)]
    order = sorted(range(4), key=lambda suit: signatures[suit], reverse=True)
    return tuple(channel[order].copy() for channel in channels)


def _betting_features_from_tensor(tensor, *, postflop):
    pairs = np.asarray(tensor[106:162], dtype=np.float32).reshape(28, 2)
    active = np.flatnonzero(np.any(pairs != 0.0, axis=1))
    split = len(active)
    if postflop and len(active) > 1:
        gaps = np.flatnonzero(np.diff(active) > 1)
        if len(gaps):
            split = int(gaps[0]) + 1
    per_round = (active[:split], active[split:]) if postflop else (active, ())
    actions = np.zeros((2, 5, 3), dtype=np.float32)
    for round_id, indices in enumerate(per_round):
        if len(indices) > 5:
            raise ValueError("OpenSpiel FHP betting round exceeds five actions")
        for slot, index in enumerate(indices):
            pair = tuple(int(value) for value in pairs[int(index)])
            token = {(1, 0): 0, (0, 1): 1, (1, 1): 1}.get(pair)
            if token is None:
                raise ValueError(f"Unsupported OpenSpiel FHP action bits: {pair}")
            actions[round_id, slot, token] = 1.0
    return np.asarray([0., 1.] if postflop else [1., 0.], dtype=np.float32), actions.reshape(-1)


def _five_card_category(hole, board):
    result = np.zeros(9, dtype=np.float32)
    cards = hole + board
    if int(cards.sum()) != 5:
        return result
    rank_counts = cards.sum(axis=0).astype(np.int8)
    suit_counts = cards.sum(axis=1).astype(np.int8)
    present = rank_counts > 0
    straight = any(np.all(present[start:start + 5]) for start in range(9))
    straight = bool(straight or np.all(present[[12, 0, 1, 2, 3]]))
    flush = bool(np.max(suit_counts) == 5)
    multiplicities = sorted((int(value) for value in rank_counts if value), reverse=True)
    if straight and flush:
        category = 8
    elif multiplicities[0] == 4:
        category = 7
    elif multiplicities[:2] == [3, 2]:
        category = 6
    elif flush:
        category = 5
    elif straight:
        category = 4
    elif multiplicities[0] == 3:
        category = 3
    elif multiplicities[:2] == [2, 2]:
        category = 2
    elif multiplicities[0] == 2:
        category = 1
    else:
        category = 0
    result[category] = 1.
    return result


class FHPFeatureEncoder:
    policy_size = FEATURE_SIZE

    def __init__(self, *, cache_entries=4096):
        self.cache_entries = int(cache_entries)
        if self.cache_entries < 0:
            raise ValueError("cache_entries cannot be negative")
        self._information_cache = OrderedDict()

    def metadata(self):
        # Same v1 metadata as the source; full-state layout records provenance,
        # not a supported input path. This port intentionally has no full_state().
        return dict(id=ENCODER_ID, version=1, lossless_modulo_suit_symmetry=True,
                    policy_layout=dict(name="player_information_state", total_size=183, card_size=104),
                    full_state_layout=dict(name="critic_full_state", total_size=263, card_size=156),
                    card_order="channel_suit_rank",
                    betting_encoding="two_rounds_five_slots_fold_call_raise_one_hot")

    def information_state(self, state, player=None):
        player = int(state.current_player() if player is None else player)
        if player not in (0, 1):
            raise ValueError("A policy information state requires player 0 or 1")
        key = (tuple(state.history()), player)
        if key in self._information_cache:
            self._information_cache.move_to_end(key)
            return self._information_cache[key]
        tensor = np.asarray(state.information_state_tensor(player), dtype=np.float32)
        if tensor.shape != (190,):
            raise ValueError("Structured encoder requires the 190-value FHP tensor")
        raw_hole = tensor[2:54].reshape(13, 4).T.copy()
        raw_board = tensor[54:106].reshape(13, 4).T.copy()
        hole, board = _canonicalise_suits(raw_hole, raw_board)
        round_one_hot, betting = _betting_features_from_tensor(tensor, postflop=bool(raw_board.sum()))
        player_one_hot = np.zeros(2, dtype=np.float32)
        player_one_hot[player] = 1.
        hole_flags = np.asarray([float(np.max(hole.sum(axis=0)) == 2),
                                 float(np.max(hole.sum(axis=1)) == 2)], dtype=np.float32)
        features = np.concatenate([
            hole.reshape(-1), board.reshape(-1), player_one_hot, round_one_hot, betting,
            hole.sum(axis=0, dtype=np.float32) / 2., board.sum(axis=0, dtype=np.float32) / 3.,
            hole.sum(axis=1, dtype=np.float32) / 2., board.sum(axis=1, dtype=np.float32) / 3.,
            hole_flags, _five_card_category(hole, board),
        ]).astype(np.float32, copy=False)
        if features.shape != (self.policy_size,):
            raise AssertionError("Structured input layout changed")
        if self.cache_entries:
            self._information_cache[key] = features
            if len(self._information_cache) > self.cache_entries:
                self._information_cache.popitem(last=False)
        return features


def encoder_from_metadata(metadata):
    if metadata is None:
        return None
    encoder = FHPFeatureEncoder()
    if metadata != encoder.metadata():
        raise ValueError("Unknown or incompatible SD-CFR feature encoder metadata")
    return encoder
